# Variables: un lugar donde se almacena un contenido
# Todas las variables pueden cambiar sus valores

# Variables de texto
name = 'Joshua'
lastname = 'Arnao'

# Texto con saltos de línea (STR)
description = '''
Hello:
How are u?
'''

# Variables númericas (INT)
age = 30
year = 2025

# Variable Vacía None = null || undefined (NoneType)
newType = None

# id() -> Dará una ubicación de esa variable en relación a la memoría del dispositivo

# Declaración de variables en una misma línea
month, day = 'Febrery', 28


# del -> Elimina la variable de la memoria
del month
